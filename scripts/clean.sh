# Remove everything that can be regenerated, leaving the tracked source plus
# the built packages. Useful before moving or archiving the project.
#
#   scripts/clean.sh          what would go, and how big
#   scripts/clean.sh --yes    actually remove it
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

targets=(
  "sdk:OpenWrt SDKs and build trees:scripts/build-packages.sh re-downloads them"
  "ref:vendored LuCI source:git clone https://git.openwrt.org/project/luci.git ref/luci"
  "img:OpenWrt images:downloads.openwrt.org"
  "dist/*.log:build logs:regenerated by the next build"
)

total=0
for t in "${targets[@]}"; do
  path="${t%%:*}"; rest="${t#*:}"; what="${rest%%:*}"; how="${rest#*:}"
  size=$(du -shc $ROOT/$path 2>/dev/null | tail -1 | cut -f1 || true)
  [ -n "${size:-}" ] || continue
  printf '  %-12s %-8s %s\n' "$path" "$size" "$what"
  printf '  %-12s %-8s (%s)\n' "" "" "$how"
done

if [ "${1:-}" = "--yes" ]; then
  rm -rf "$ROOT"/sdk "$ROOT"/ref "$ROOT"/img
  rm -f "$ROOT"/dist/*.log
  echo "removed. The tracked source and dist/*.ipk|*.apk are untouched."
else
  echo
  echo "nothing removed — pass --yes to do it."
fi
